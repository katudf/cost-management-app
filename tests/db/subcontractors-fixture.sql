-- 日報の RPC・承認・LINE WORKS などは含めない（このマイグレーションは save_daily_report を再定義しない）。
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN CREATE ROLE authenticated; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN CREATE ROLE anon; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='service_role') THEN CREATE ROLE service_role; END IF;
END $$;

CREATE SCHEMA auth;
CREATE SCHEMA extensions;
GRANT USAGE ON SCHEMA auth, extensions, public TO authenticated, anon, service_role;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
  SELECT NULLIF(current_setting('request.jwt.claim.sub', true), '')::uuid;
$$;

CREATE TABLE public.office_staff (
  id bigint PRIMARY KEY,
  name text,
  auth_user_id uuid UNIQUE,
  role text CHECK (role IN ('admin', 'system_admin', 'office', 'worker', 'viewer'))
);

CREATE FUNCTION public.is_admin() RETURNS boolean LANGUAGE sql SECURITY DEFINER STABLE SET search_path = public AS $$
  SELECT EXISTS (SELECT 1 FROM office_staff WHERE auth_user_id = auth.uid() AND role IN ('admin', 'system_admin'));
$$;
CREATE FUNCTION public.is_staff() RETURNS boolean LANGUAGE sql SECURITY DEFINER STABLE SET search_path = public AS $$
  SELECT EXISTS (SELECT 1 FROM office_staff WHERE auth_user_id = auth.uid());
$$;
CREATE FUNCTION public.current_staff_role() RETURNS text LANGUAGE sql SECURITY DEFINER STABLE SET search_path = public AS $$
  SELECT COALESCE((SELECT role FROM office_staff WHERE auth_user_id = auth.uid() LIMIT 1), 'none');
$$;
CREATE FUNCTION public.is_office_or_admin() RETURNS boolean LANGUAGE sql SECURITY DEFINER STABLE SET search_path = public AS $$
  SELECT COALESCE(public.is_admin() OR public.current_staff_role() = 'office', false);
$$;
CREATE FUNCTION public.is_personal_worker() RETURNS boolean LANGUAGE sql STABLE AS $$ SELECT false; $$;
-- 職長判定の代用品: worker_id が Projects.foreman_worker_id と一致し、名前が Workers の名前と一致すること
CREATE TABLE public."Workers" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  name text,
  display_order integer,
  worker_type text NOT NULL DEFAULT '職人',
  resignation_date date,
  show_in_assignment boolean NOT NULL DEFAULT true
);
ALTER TABLE public."Workers" ENABLE ROW LEVEL SECURITY;
CREATE POLICY workers_office_all ON public."Workers" TO authenticated
  USING (is_admin() OR current_staff_role() = 'office')
  WITH CHECK (is_admin() OR current_staff_role() = 'office');
GRANT SELECT, INSERT, UPDATE, DELETE ON public."Workers" TO authenticated;

CREATE VIEW public.workers_directory AS
  SELECT id, name, display_order, worker_type, resignation_date, show_in_assignment
  FROM public."Workers" WHERE is_staff() OR is_personal_worker();
GRANT SELECT ON public.workers_directory TO authenticated;

CREATE TABLE public."Projects" (id bigint PRIMARY KEY, name text, foreman_worker_id bigint);
CREATE FUNCTION public.is_declared_foreman(p_project_id bigint, p_worker_id bigint, p_worker_name text)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (
    SELECT 1 FROM "Projects" p JOIN "Workers" w ON w.id = p.foreman_worker_id
     WHERE p.id = p_project_id AND w.id = p_worker_id AND w.name = p_worker_name
  );
$$;

CREATE TABLE public."Assignments" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date date,
  "workerId" bigint REFERENCES public."Workers"(id),
  "projectId" bigint
);

CREATE TABLE public."SubcontractorRecords" (
  id uuid NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  project_id int4 NOT NULL,
  date date NOT NULL,
  company_name text NOT NULL,
  worker_count numeric NOT NULL,
  unit_price numeric NOT NULL DEFAULT 0,
  worker_name text
);
ALTER TABLE public."SubcontractorRecords" ENABLE ROW LEVEL SECURITY;
CREATE POLICY subcontractor_records_office_all ON public."SubcontractorRecords" TO authenticated
  USING (is_admin() OR current_staff_role() = 'office')
  WITH CHECK (is_admin() OR current_staff_role() = 'office');
CREATE POLICY subcontractor_records_select_worker ON public."SubcontractorRecords" FOR SELECT TO authenticated
  USING (current_staff_role() = 'worker');
GRANT SELECT, INSERT, UPDATE, DELETE ON public."SubcontractorRecords" TO authenticated;


-- 下請け会社の正式管理 マイグレーションA（追加のみ。既存の挙動は変えない）
-- 設計: docs/specs/subcontractors.md
--   - Subcontractors（会社マスタ）/ SubcontractContracts（現場×会社の契約。常用・請負）
--   - Workers.subcontractor_id（配置表用の行を会社と1対1に紐づける）と、その同期・保護トリガー
--   - SubcontractorRecords.subcontractor_id と、会社の照合・暫定契約・単価コピーを一元化する BEFORE トリガー
--   - Assignments.planned_count（予定人数）

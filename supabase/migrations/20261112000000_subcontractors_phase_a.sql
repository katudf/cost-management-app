-- ---------- 4. Workers の保護トリガー（下請けの配置行） ----------
-- subcontractor_id のある行は、名前・紐づけの手編集と DELETE を拒否する。
-- 同期トリガーだけが app.bypass_subcontractor_sync で許可される。display_order（配置表の並び替え）は許可する。
CREATE OR REPLACE FUNCTION public.protect_workers_subcontractor_row()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF coalesce(current_setting('app.bypass_subcontractor_sync', true), 'off') = 'on' THEN
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
  END IF;

  IF TG_OP = 'INSERT' THEN
    IF NEW.subcontractor_id IS NOT NULL THEN
      RAISE EXCEPTION '下請け会社の配置行は、下請け会社マスタから登録してください。';
    END IF;
    RETURN NEW;
  END IF;

  IF TG_OP = 'DELETE' THEN
    IF OLD.subcontractor_id IS NOT NULL THEN
      RAISE EXCEPTION '下請け会社の配置行は削除できません。下請け会社マスタで無効にしてください。';
    END IF;
    RETURN OLD;
  END IF;

  IF NEW.subcontractor_id IS DISTINCT FROM OLD.subcontractor_id THEN
    RAISE EXCEPTION '下請け会社との紐づけは変更できません。';
  END IF;
  IF OLD.subcontractor_id IS NOT NULL
     AND (NEW.name IS DISTINCT FROM OLD.name
          OR NEW.show_in_assignment IS DISTINCT FROM OLD.show_in_assignment
          OR NEW.resignation_date IS DISTINCT FROM OLD.resignation_date) THEN
    RAISE EXCEPTION '下請け会社の配置行の名前・表示は、下請け会社マスタから変更してください。';
  END IF;
  RETURN NEW;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.protect_workers_subcontractor_row() FROM anon, authenticated, PUBLIC;

DROP TRIGGER IF EXISTS trg_protect_workers_subcontractor_row ON public."Workers";
CREATE TRIGGER trg_protect_workers_subcontractor_row
  BEFORE INSERT OR UPDATE OR DELETE ON public."Workers"
  FOR EACH ROW EXECUTE FUNCTION public.protect_workers_subcontractor_row();

-- ---------- 5. Subcontractors → Workers / SubcontractorRecords の同期 ----------
-- app.skip_subcontractor_worker_create = 'on' のときは Workers 行を作らない（既存の Workers 行を紐づける移行用）。
CREATE OR REPLACE FUNCTION public.sync_subcontractor_worker()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  PERFORM set_config('app.bypass_subcontractor_sync', 'on', true);

  IF TG_OP = 'INSERT' THEN
    IF coalesce(current_setting('app.skip_subcontractor_worker_create', true), 'off') <> 'on' THEN
      INSERT INTO public."Workers" (name, worker_type, display_order, show_in_assignment, subcontractor_id)
      VALUES (
        NEW.name,
        '作業員',
        COALESCE((SELECT max(display_order) FROM public."Workers"), 0) + 1,
        NEW.show_in_assignment AND NEW.active,
        NEW.id
      );
    END IF;
  ELSE
    IF NEW.name IS DISTINCT FROM OLD.name
       OR NEW.show_in_assignment IS DISTINCT FROM OLD.show_in_assignment
       OR NEW.active IS DISTINCT FROM OLD.active THEN
      UPDATE public."Workers"
         SET name = NEW.name,
             show_in_assignment = NEW.show_in_assignment AND NEW.active
       WHERE subcontractor_id = NEW.id;
    END IF;
    -- 日報の記録の会社名（表示用コピー）も最新の名前にする
    IF NEW.name IS DISTINCT FROM OLD.name THEN
      UPDATE public."SubcontractorRecords"
         SET company_name = NEW.name
       WHERE subcontractor_id = NEW.id;
    END IF;
  END IF;

  PERFORM set_config('app.bypass_subcontractor_sync', 'off', true);
  RETURN NEW;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.sync_subcontractor_worker() FROM anon, authenticated, PUBLIC;

DROP TRIGGER IF EXISTS trg_sync_subcontractor_worker ON public."Subcontractors";
CREATE TRIGGER trg_sync_subcontractor_worker
  AFTER INSERT OR UPDATE ON public."Subcontractors"
  FOR EACH ROW EXECUTE FUNCTION public.sync_subcontractor_worker();

-- ---------- 6. 請負期間の判定（SQL 側の正本） ----------
-- その日が、同じ現場・同じ会社の請負契約の期間（両端を含む。終了日 NULL は継続中）に含まれるか。
CREATE OR REPLACE FUNCTION public._subcontractor_in_ukeoi(p_project_id bigint, p_subcontractor_id bigint, p_date date)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT p_subcontractor_id IS NOT NULL
     AND EXISTS (
       SELECT 1 FROM public."SubcontractContracts" c
        WHERE c.project_id = p_project_id
          AND c.subcontractor_id = p_subcontractor_id
          AND c.type = '請負'
          AND p_date BETWEEN c.start_date AND COALESCE(c.end_date, '9999-12-31'::date)
     );
$$;

REVOKE EXECUTE ON FUNCTION public._subcontractor_in_ukeoi(bigint, bigint, date) FROM anon, authenticated, PUBLIC;

-- ---------- 7. SubcontractorRecords の BEFORE トリガー ----------
-- 日報保存 RPC・管理画面の直接書き込み・将来のインポートが、同じ規則を通る。
--   1. 会社の照合（subcontractor_id ↔ company_name）。一致しなければ NULL のまま保存し、拒否しない
--   2. 請負期間外なら、常用契約を確保する（無ければ暫定契約を作る）
--   3. unit_price が 0/NULL なら、常用契約の単価をコピーする（会社が変わる UPDATE では常に再コピー）
CREATE OR REPLACE FUNCTION public.subcontractor_record_prepare()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_sub public."Subcontractors"%ROWTYPE;
  v_contract public."SubcontractContracts"%ROWTYPE;
  v_explicit_sub boolean;
  v_sub_changed boolean := false;
BEGIN
  IF TG_OP = 'INSERT' THEN
    v_explicit_sub := NEW.subcontractor_id IS NOT NULL;
  ELSE
    v_explicit_sub := NEW.subcontractor_id IS DISTINCT FROM OLD.subcontractor_id;
  END IF;

  IF v_explicit_sub AND NEW.subcontractor_id IS NOT NULL THEN
    -- 会社が明示された: 会社マスタの名前で company_name を揃える
    SELECT * INTO v_sub FROM public."Subcontractors" WHERE id = NEW.subcontractor_id;
    IF NOT FOUND THEN
      RAISE EXCEPTION '下請け会社が見つかりません (id=%)。', NEW.subcontractor_id;
    END IF;
    NEW.company_name := v_sub.name;
    v_sub_changed := true;
  ELSIF TG_OP = 'INSERT' OR NEW.company_name IS DISTINCT FROM OLD.company_name OR v_explicit_sub THEN
    -- 会社名から照合する（一致しなければ NULL）
    SELECT * INTO v_sub FROM public."Subcontractors"
     WHERE public.normalize_company_name(name) = public.normalize_company_name(NEW.company_name)
       AND public.normalize_company_name(NEW.company_name) <> ''
     LIMIT 1;
    IF FOUND THEN
      NEW.subcontractor_id := v_sub.id;
      NEW.company_name := v_sub.name;
    ELSE
      NEW.subcontractor_id := NULL;
    END IF;
    v_sub_changed := TG_OP = 'INSERT' OR NEW.subcontractor_id IS DISTINCT FROM OLD.subcontractor_id;
  END IF;

  IF NEW.subcontractor_id IS NULL THEN
    RETURN NEW;
  END IF;

  -- 請負期間内の記録は常用の原価に入らないので、契約の確保と単価コピーは不要
  IF public._subcontractor_in_ukeoi(NEW.project_id::bigint, NEW.subcontractor_id, NEW.date) THEN
    RETURN NEW;
  END IF;

  IF NOT (TG_OP = 'INSERT' OR v_sub_changed) THEN
    RETURN NEW;
  END IF;

  SELECT * INTO v_contract FROM public."SubcontractContracts"
   WHERE project_id = NEW.project_id::bigint AND subcontractor_id = NEW.subcontractor_id AND type = '常用'
   FOR SHARE;
  IF NOT FOUND THEN
    IF v_sub.id IS NULL THEN
      SELECT * INTO v_sub FROM public."Subcontractors" WHERE id = NEW.subcontractor_id;
    END IF;
    INSERT INTO public."SubcontractContracts" (project_id, subcontractor_id, type, unit_price, needs_review)
    VALUES (NEW.project_id::bigint, NEW.subcontractor_id, '常用', v_sub.standard_unit_price, true)
    ON CONFLICT (project_id, subcontractor_id) WHERE type = '常用' DO NOTHING;
    SELECT * INTO v_contract FROM public."SubcontractContracts"
     WHERE project_id = NEW.project_id::bigint AND subcontractor_id = NEW.subcontractor_id AND type = '常用'
     FOR SHARE;
  END IF;

  -- 会社が別の会社に変わる UPDATE では常に再コピーする。未紐づけ（NULL）から紐づく場合は、入っている単価を残す
  IF FOUND AND (COALESCE(NEW.unit_price, 0) = 0
                OR (TG_OP = 'UPDATE' AND v_sub_changed AND OLD.subcontractor_id IS NOT NULL)) THEN
    NEW.unit_price := COALESCE(v_contract.unit_price, 0);
  END IF;

  RETURN NEW;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.subcontractor_record_prepare() FROM anon, authenticated, PUBLIC;

DROP TRIGGER IF EXISTS trg_subcontractor_record_prepare ON public."SubcontractorRecords";
CREATE TRIGGER trg_subcontractor_record_prepare
  BEFORE INSERT OR UPDATE ON public."SubcontractorRecords"
  FOR EACH ROW EXECUTE FUNCTION public.subcontractor_record_prepare();

-- ---------- 8. RPC ----------
-- 暫定契約の確定: 契約の単価を確定し、その契約の対象記録（単価 0/NULL・請負期間外）の単価を一括更新する。
CREATE OR REPLACE FUNCTION public.confirm_subcontract_contract(p_contract_id uuid, p_unit_price numeric)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_contract public."SubcontractContracts"%ROWTYPE;
  v_count integer;
BEGIN
  IF NOT public.is_office_or_admin() THEN
    RAISE EXCEPTION '契約を確定する権限がありません。' USING ERRCODE = '42501';
  END IF;
  IF p_unit_price IS NULL OR p_unit_price < 0 THEN
    RAISE EXCEPTION '単価が不正です。' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO v_contract FROM public."SubcontractContracts" WHERE id = p_contract_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION '契約が見つかりません。' USING ERRCODE = 'P0002';
  END IF;
  IF v_contract.type <> '常用' THEN
    RAISE EXCEPTION '常用の契約だけ確定できます。' USING ERRCODE = '22023';
  END IF;

  UPDATE public."SubcontractContracts"
     SET unit_price = p_unit_price, needs_review = false
   WHERE id = p_contract_id;

  UPDATE public."SubcontractorRecords" r
     SET unit_price = p_unit_price
   WHERE r.project_id = v_contract.project_id
     AND r.subcontractor_id = v_contract.subcontractor_id
     AND COALESCE(r.unit_price, 0) = 0
     AND NOT public._subcontractor_in_ukeoi(r.project_id::bigint, r.subcontractor_id, r.date);
  GET DIAGNOSTICS v_count = ROW_COUNT;

  RETURN v_count;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.confirm_subcontract_contract(uuid, numeric) FROM anon, PUBLIC;
GRANT EXECUTE ON FUNCTION public.confirm_subcontract_contract(uuid, numeric) TO authenticated;

-- 職長向け: 現場の協力業者費の合計（常用 + 請負）だけを返す。単価・契約は返さない。
--   常用 = 請負期間外の記録の 人数 × 記録の単価（subcontractor_id が NULL の旧記録も常用として計上）
--   請負 = 請負契約の契約金額（登録時に全額）
CREATE OR REPLACE FUNCTION public.get_project_subcontract_cost(
  p_project_id bigint, p_worker_id bigint, p_worker_name text
)
RETURNS numeric
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_joyo numeric;
  v_ukeoi numeric;
BEGIN
  IF NOT (public.is_office_or_admin() OR public.is_declared_foreman(p_project_id, p_worker_id, p_worker_name)) THEN
    RAISE EXCEPTION '協力業者費を取得する権限がありません。' USING ERRCODE = '42501';
  END IF;

  SELECT COALESCE(sum(r.worker_count * COALESCE(r.unit_price, 0)), 0) INTO v_joyo
    FROM public."SubcontractorRecords" r
   WHERE r.project_id = p_project_id
     AND NOT public._subcontractor_in_ukeoi(r.project_id::bigint, r.subcontractor_id, r.date);

  SELECT COALESCE(sum(c.contract_amount), 0) INTO v_ukeoi
    FROM public."SubcontractContracts" c
   WHERE c.project_id = p_project_id AND c.type = '請負';

  RETURN v_joyo + v_ukeoi;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.get_project_subcontract_cost(bigint, bigint, text) FROM anon, PUBLIC;
GRANT EXECUTE ON FUNCTION public.get_project_subcontract_cost(bigint, bigint, text) TO authenticated;


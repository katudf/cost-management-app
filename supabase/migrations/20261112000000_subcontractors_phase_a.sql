-- ---------- 2. SubcontractContracts（現場×会社の契約） ----------
CREATE TABLE IF NOT EXISTS public."SubcontractContracts" (
  id uuid NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  project_id bigint NOT NULL REFERENCES public."Projects"(id) ON DELETE CASCADE,
  subcontractor_id bigint NOT NULL REFERENCES public."Subcontractors"(id),
  type text NOT NULL,
  unit_price numeric,
  contract_amount numeric,
  scope text,
  start_date date,
  end_date date,
  needs_review boolean NOT NULL DEFAULT false,
  CONSTRAINT subcontract_contracts_type_check CHECK (type IN ('常用', '請負')),
  CONSTRAINT subcontract_contracts_joyo_check
    CHECK (type <> '常用' OR (unit_price IS NOT NULL AND unit_price >= 0)),
  CONSTRAINT subcontract_contracts_ukeoi_check
    CHECK (type <> '請負' OR (contract_amount IS NOT NULL AND contract_amount >= 0 AND start_date IS NOT NULL)),
  CONSTRAINT subcontract_contracts_period_check
    CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);

